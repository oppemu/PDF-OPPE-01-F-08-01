    // Match the entire name after cosmetic cleanup only. Never use a partial or fuzzy match.
    function normalizeName(value) {
        let name = String(value == null ? '' : value).normalize('NFC')
            .replace(/[\u200b-\u200d\ufeff]/g, '').replace(/\s+/g, ' ').trim();
        const prefix = /^(?:รองศาสตราจารย์|ผู้ช่วยศาสตราจารย์|ศาสตราจารย์|นายแพทย์|แพทย์หญิง|ทันตแพทย์หญิง|ทันตแพทย์|นางสาว|น\.\s*ส\.|ด\.\s*ช\.|ด\.\s*ญ\.|ว่าที่\s*ร\.\s*ต\.|ม\.\s*ร\.\s*ว\.|ม\.\s*ล\.|ผศ\.|รศ\.|ศ\.|ดร\.|นพ\.|พญ\.|ทพญ\.|ทพ\.|ภญ\.|ภก\.|นาง|นาย|อาจารย์|Mr\.|Mrs\.|Ms\.|Dr\.|Prof\.)\s*/i;
        while (prefix.test(name)) name = name.replace(prefix, '').trim();
        return name.replace(/\s+/g, ' ').trim();
    }
    function createLookup(rows) {
        const names = new Map();
        for (const contact of rows) {
            const key = normalizeName(contact.name);
            if (!key) continue;
            const matches = names.get(key) || [];
            matches.push(contact);
            names.set(key, matches);
        }
        return value => {
            const key = normalizeName(value);
            if (!key) return { status: 'missing-name', contact: null };
            const matches = names.get(key) || [];
            if (!matches.length) return { status: 'not-found', contact: null };
            // Even identical duplicate rows require review; never silently choose one person.
            if (matches.length !== 1) return { status: 'ambiguous', contact: null };
            const contact = matches[0];
            return { status: contact.extension ? 'matched' : 'missing-extension', contact };
        };
    }
